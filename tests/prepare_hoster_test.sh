#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT_DIR="/tmp/humoco-hoster-test"
SERVER_BIN=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --out-dir)
      OUT_DIR="${2:-}"
      shift 2
      ;;
    --bin)
      SERVER_BIN="${2:-}"
      shift 2
      ;;
    -h|--help)
      echo "Usage: $0 [--out-dir /tmp/humoco-hoster-test] [--bin /path/to/humoco-sync-server]"
      exit 0
      ;;
    *)
      echo "Unknown option: $1" >&2
      exit 1
      ;;
  esac
done

if [[ -z "$SERVER_BIN" ]]; then
  SERVER_BIN="${ROOT_DIR}/rust/target/debug/humoco-sync-server"
  if [[ ! -x "$SERVER_BIN" ]]; then
    echo "Building humoco-sync-server (offline)..." >&2
    cargo build --offline --manifest-path "${ROOT_DIR}/rust/Cargo.toml" >&2
  fi
fi

read -r ADMIN_SK ADMIN_PK <<< "$("$SERVER_BIN" sign-test keygen)"
DATA_DIR="d-locktest-$(od -tx1 -An -N4 /dev/urandom | tr -d ' \n')"
UPLOAD_DIR="${OUT_DIR%/}/upload/humoco-lock-test"

rm -rf "${OUT_DIR}"
mkdir -p "$UPLOAD_DIR"

cp \
  "${ROOT_DIR}/php/sync.php" \
  "${ROOT_DIR}/php/lock_handler.php" \
  "${ROOT_DIR}/php/lock_rotation.php" \
  "${ROOT_DIR}/php/.htaccess" \
  "${ROOT_DIR}/php/robots.txt" \
  "${ROOT_DIR}/php/index.html" \
  "$UPLOAD_DIR/"

cat > "${UPLOAD_DIR}/config.php" <<EOF
<?php // Disposable config.php generated by prepare_hoster_test.sh
return [
    'admin_pubkey'         => '${ADMIN_PK}',
    'data_dir'             => '${DATA_DIR}',
    'register_url'         => null,
    'max_members'          => 300,
    'max_total_storage_mb' => 256,
    'disable_rate_limit'   => false,
    'channels' => [
        'card'   => ['max_bytes' => 524288,  'ttl_days' => 30],
        'wot'    => ['max_bytes' => 524288,  'ttl_days' => 30],
        'backup' => ['max_bytes' => 5242880, 'ttl_days' => 180],
        'post'   => ['max_bytes' => 524288,  'ttl_days' => 21],
        'media'  => [
            'max_bytes'      => 102400,
            'max_user_count' => 5,
            'max_user_bytes' => 409600,
            'max_channel_mb' => 100,
            'ttl_days'       => 180,
        ],
    ],
    'lock' => [
        'enabled'               => true,
        'max_retention_quarter' => 8159,
        'max_inodes'            => 50000,
        'pow_base_bits'         => 8,
        'allow_pow_tickets'     => false,
        'ticket_pow_bits'       => 16,
    ],
];
EOF

umask 077
printf '%s\n' "$ADMIN_SK" > "${OUT_DIR%/}/.admin_sk"
chmod 600 "${OUT_DIR%/}/.admin_sk"
umask 022

cat > "${OUT_DIR%/}/run_test.sh" <<EOF
#!/usr/bin/env bash
set -euo pipefail

if [[ \$# -lt 1 || "\$1" == "-h" || "\$1" == "--help" ]]; then
  echo "Usage: \$0 <URL-zum-Ordner-oder-sync.php>"
  echo "Beispiel: \$0 https://deine-domain.de/humoco-lock-test"
  exit 0
fi

RAW_URL="\${1%/}"
if [[ "\$RAW_URL" == */sync.php || "\$RAW_URL" == */sync ]]; then
  SYNC_URL="\$RAW_URL"
else
  SYNC_URL="\${RAW_URL}/sync.php"
fi

ADMIN_SK="\$(tr -d ' \t\r\n' < "${OUT_DIR%/}/.admin_sk")"
REPORT_FILE="${OUT_DIR%/}/report.md"

"${ROOT_DIR}/tests/measure_hoster.sh" \\
  --url "\$SYNC_URL" \\
  --admin-sk "\$ADMIN_SK" \\
  --concurrency 10 \\
  --samples 15 \\
  --out "\$REPORT_FILE"

echo ""
echo "========================================================================"
echo " Test abgeschlossen! Bericht gespeichert unter: \$REPORT_FILE"
echo " Wichtig: Bitte den Ordner 'humoco-lock-test' danach auf dem Hoster"
echo " wieder loeschen (Sicherheit / Aufraeumen)."
echo "========================================================================"
EOF
chmod +x "${OUT_DIR%/}/run_test.sh"

echo "Bereitgestellt unter: ${OUT_DIR%/}"
echo "  1. Upload-Ordner (auf den Hoster kopieren): ${UPLOAD_DIR}"
echo "  2. Testskript (danach lokal ausfuehren):    ${OUT_DIR%/}/run_test.sh <URL>"
